import { resolvePackagePath } from '@backstage/backend-plugin-api';
import chalk from 'chalk';
import fs from 'fs-extra';
import { loadYaml } from '../../../../../lib/yaml';
import { dirname, join, resolve } from 'node:path';
import {
  OLD_SCHEMA_PATH,
  OPENAPI_IGNORE_FILES,
  OUTPUT_PATH,
  TS_SCHEMA_PATH,
} from '../../../../../lib/openapi/constants';
import { deduplicateImports } from '../../../../../lib/openapi/dedupe-imports';
import { targetPaths } from '@backstage/cli-common';
import { runOutputWithStderr } from '../../../../../lib/runOutputWithStderr';
import { backstageCliCommand } from '../../../../../lib/backstageCli';
import {
  getOpenApiGeneratorKey,
  getPathToCurrentOpenApiSpec,
  getRelativePathToFile,
  toGeneratorAdditionalProperties,
} from '../../../../../lib/openapi/helpers';

/**
 * Writes the router and index files, returning the path of the index file.
 */
async function writeSpecFiles() {
  const openapiPath = await getPathToCurrentOpenApiSpec();
  const yaml = loadYaml(await fs.readFile(openapiPath, 'utf8'));

  const tsPath = targetPaths.resolve(TS_SCHEMA_PATH);

  const schemaDir = dirname(tsPath);
  await fs.mkdirp(schemaDir);

  const oldTsPath = targetPaths.resolve(OLD_SCHEMA_PATH);
  if (fs.existsSync(oldTsPath)) {
    console.warn(`Removing old schema file at ${oldTsPath}`);
    fs.removeSync(oldTsPath);
  }

  // The first set of comment slashes allow for the eslint notice plugin to run
  // with onNonMatchingHeader: 'replace', as is the case in the open source
  // Backstage repo. Otherwise the auto-generated comment will be removed by the
  // lint run that follows once all the files are written.
  await fs.writeFile(
    tsPath,
    `//

// ******************************************************************
// * THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY. *
// ******************************************************************
import {createValidatedOpenApiRouterFromGeneratedEndpointMap} from '@backstage/backend-openapi-utils';
import {EndpointMap} from './apis';
export const spec = ${JSON.stringify(yaml, null, 2)} as const;
export const createOpenApiRouter = async (
  options?: Parameters<typeof createValidatedOpenApiRouterFromGeneratedEndpointMap>['1'],
) => createValidatedOpenApiRouterFromGeneratedEndpointMap<EndpointMap>(spec, options);
`,
  );

  const indexFile = join(schemaDir, '..', 'index.ts');
  await fs.writeFile(
    indexFile,
    `//
    export * from './generated';`,
  );

  return indexFile;
}

async function generate(
  serverAdditionalProperties?: string,
  abortSignal?: AbortController,
) {
  const resolvedOpenapiPath = await getPathToCurrentOpenApiSpec();
  const resolvedOutputDirectory = await getRelativePathToFile(OUTPUT_PATH);

  await fs.emptyDir(resolvedOutputDirectory);

  await fs.writeFile(
    resolve(resolvedOutputDirectory, '.openapi-generator-ignore'),
    OPENAPI_IGNORE_FILES.join('\n'),
  );

  const additionalProperties = toGeneratorAdditionalProperties({
    initialValue: serverAdditionalProperties,
  });
  const generatorKey = await getOpenApiGeneratorKey(resolvedOpenapiPath);

  await runOutputWithStderr(
    [
      'node',
      resolvePackagePath('@openapitools/openapi-generator-cli', 'main.js'),
      'generate',
      '-i',
      resolvedOpenapiPath,
      '-o',
      resolvedOutputDirectory,
      '-g',
      'typescript',
      '-c',
      resolvePackagePath(
        '@backstage/repo-tools',
        'templates/typescript-backstage-server.yaml',
      ),
      '--generator-key',
      generatorKey,
      ...(additionalProperties
        ? [`--additional-properties=${additionalProperties}`]
        : []),
    ],
    {
      cwd: resolvePackagePath('@backstage/repo-tools'),
      signal: abortSignal?.signal,
    },
  );

  // Deduplicate imports in generated files
  const generatedFiles = await fs.readdir(resolvedOutputDirectory);
  for (const file of generatedFiles) {
    if (file.endsWith('.ts')) {
      deduplicateImports(resolve(resolvedOutputDirectory, file));
    }
  }

  fs.removeSync(resolve(resolvedOutputDirectory, '.openapi-generator-ignore'));
  fs.removeSync(resolve(resolvedOutputDirectory, '.gitattributes'));

  fs.rmSync(resolve(resolvedOutputDirectory, 'docs'), {
    recursive: true,
    force: true,
  });
  fs.rmSync(resolve(resolvedOutputDirectory, '.openapi-generator'), {
    recursive: true,
    force: true,
  });

  // The router and index files are written before linting and formatting, so
  // that all the generated files are covered by a single run of each
  const indexFile = await writeSpecFiles();
  const generatedPaths = [resolvedOutputDirectory, indexFile];

  await runOutputWithStderr(
    [...backstageCliCommand(), 'package', 'lint', '--fix', ...generatedPaths],
    { signal: abortSignal?.signal },
  );

  const prettier = targetPaths.resolveRoot('node_modules/.bin/prettier');
  if (await fs.pathExists(prettier)) {
    // Run in the project root, since Prettier only reads the ignore file of
    // its working directory
    await runOutputWithStderr([prettier, '--write', ...generatedPaths], {
      cwd: targetPaths.rootDir,
      signal: abortSignal?.signal,
    });
  }
}

export async function command(
  {
    abortSignal,
    isWatch = false,
  }: {
    abortSignal?: AbortController;
    isWatch?: boolean;
  },
  serverAdditionalProperties?: string,
): Promise<void> {
  try {
    await generate(serverAdditionalProperties, abortSignal);
    console.log(chalk.green('Generated server files.'));
  } catch (err) {
    if (err.name === 'AbortError') {
      console.debug('Server generation aborted.');
      return;
    }
    if (isWatch) {
      console.log(chalk.red(`Server generation failed:`));
      console.group();
      console.log(chalk.red(err.message));
      console.groupEnd();
    } else {
      console.log(chalk.red(err.message));
      console.log(chalk.red(`OpenAPI server stub generation failed.`));
    }
  }
}
